enum class ThemeMode {
    SYSTEM,
    LIGHT,
    DARK
}

enum class LanguageMode(val code: String, val displayName: String, val localizedName: String) {
    ES("es", "Español", "Español"),
    EN("en", "Inglés", "English"),
    FR("fr", "Francés", "Français"),
    IT("it", "Italiano", "Italiano"),
    ZH("zh", "Chino", "中文"),
    NL("nl", "Holandés", "Nederlands"),
    DE("de", "Alemán", "Deutsch"),
    PL("pl", "Polaco", "Polski");

    companion object {
        fun fromCode(code: String): LanguageMode {
            val normalized = code.lowercase().trim()
            return entries.firstOrNull { it.code == normalized } ?: when {
                normalized.startsWith("es") -> ES
                normalized.startsWith("fr") -> FR
                normalized.startsWith("it") -> IT
                normalized.startsWith("zh") -> ZH
                normalized.startsWith("nl") -> NL
                normalized.startsWith("de") -> DE
                normalized.startsWith("pl") -> PL
                else -> EN
            }
        }
    }
}

